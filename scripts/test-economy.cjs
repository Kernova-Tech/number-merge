const fs = require('node:fs');
const ts = require('typescript');
const assert = require('node:assert/strict');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const data = new Map();
global.localStorage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value) };
const { collectDaily, readWallet, purchaseBoosters, creditReward, syncWallet } = require('../src/game/economy.ts');
const { dailyStatus, formatCountdown } = require('../src/game/dailyRewards.ts');
const start = Date.UTC(2026, 10, 11, 12);
assert.equal(collectDaily(start).gift.gems, 20);
assert.equal(readWallet().gems, 520);
assert.equal(collectDaily(start), null, 'same day cannot claim again');
assert.equal(collectDaily(start - 86400000), null, 'backward clock cannot claim');
assert.equal(dailyStatus(readWallet().daily, start).ready, false);
assert.equal(formatCountdown(1000 * 3661), '01:01:01');
assert.equal(collectDaily(start + 5 * 86400000).gift.gems, 25, 'missing days does not reset or skip rewards');
creditReward('milestone:test', 10);
assert.equal(readWallet().daily.count, 2, 'other rewards preserve the calendar');
assert.equal(collectDaily(start + 6 * 86400000).gift.booster, 'swap');
for (let day = 7; day <= 10; day++) assert(collectDaily(start + day * 86400000));
assert.equal(readWallet().daily.count, 7);
assert.equal(dailyStatus(readWallet().daily, start + 11 * 86400000).index, 0, 'seven-day cycle repeats');
const before = readWallet();
assert(purchaseBoosters('bundle'));
assert.equal(readWallet().gems, before.gems - 90);
for (const type of ['hammer', 'swap', 'undo']) assert.equal(readWallet().boosters[type], before.boosters[type] + 1);
assert.equal(readWallet().daily.count, 7, 'purchases preserve daily metadata');
syncWallet(0, readWallet().boosters);
assert.equal(purchaseBoosters('hammer'), null, 'insufficient funds rejected');
creditReward('same-receipt', 20); creditReward('same-receipt', 20);
assert.equal(readWallet().gems, 20, 'reward receipts deduplicate');
console.log('PASS: daily sequence, missed days, clock rollback, duplicate claim, cycle rollover, calendar preservation, bundle purchase, insufficient funds, reward receipts.');
